import { Alert } from "@/components/ui/alert";

/**
 * Reference data in this system ships unverified. Anywhere a value, a cluster
 * name or a clause reference is shown, the screen has to say so — a placeholder
 * presented without a marker reads as authoritative.
 */
export function UnverifiedNotice({
  title,
  body,
}: {
  title: string;
  body: string;
}) {
  return (
    <Alert tone="warn" title={<>Unverified · {title}</>} className="mb-4">
      <p className="max-w-3xl">{body}</p>
    </Alert>
  );
}

export function ClusterSourceNotice({
  clusterSource,
  clustersVerified,
  clusterCount,
}: {
  clusterSource: string;
  clustersVerified: boolean;
  clusterCount: number;
}) {
  if (clustersVerified) {
    return (
      <Alert
        tone="ok"
        title={`Verified · ${clusterCount} notified cluster(s), read back against the published list`}
        className="mb-4"
      >
        <p>{clusterSource}</p>
      </Alert>
    );
  }
  return (
    <UnverifiedNotice
      title="This notified cluster list is UNVERIFIED and must not be relied on for an eligibility determination"
      body={
        `${clusterCount} cluster(s) are held for this sector. No row has been read back against the ` +
        `official BEE list. A match found here is a prompt to check the published list, not an ` +
        `eligibility decision. Source note on record: ${clusterSource}`
      }
    />
  );
}

/**
 * Nothing this system renders is a BEE or ICM form. Shown next to every report
 * download so a generated PDF is never mistaken for a filing.
 */
export function ReportDisclaimer() {
  return (
    <p className="mt-2.5 max-w-3xl text-xs leading-relaxed text-mist-500">
      Generated by VerifyStack from the evidence and runs held in this engagement. It is a working
      document, not an official BEE or ICM form, and it has not been prepared on, or validated
      against, any prescribed template.
    </p>
  );
}
